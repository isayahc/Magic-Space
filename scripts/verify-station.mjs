import { createRequire } from 'node:module';
import { join } from 'node:path';
import { writeFile } from 'node:fs/promises';
import { root,out } from '../paths.mjs';
const require=createRequire(join(root,'package.json'));
const { chromium,expect }=require('@playwright/test');
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1600,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400 && new URL(r.url()).hostname==='127.0.0.1')errors.push(`${r.status()} ${r.url()}`);});
  await page.goto(process.env.STATION_URL||'http://127.0.0.1:4194/station');
  await expect(page.locator('body')).toHaveAttribute('data-ready','true',{timeout:120000});
  await page.getByRole('button',{name:'Pause',exact:false}).click();
  const start=await page.evaluate(()=>window.station.snapshot());
  expect(start.departments).toBe(6);expect(start.props).toBe(36);expect(start.crew.every(c=>c.skins>0)).toBe(true);
  await page.evaluate(()=>window.station.advance(18));
  const walking=await page.evaluate(()=>window.station.snapshot());
  expect(walking.crew.some(c=>c.mode==='walk'&&c.distance>1)).toBe(true);
  expect(walking.crew.some((c,i)=>JSON.stringify(c.bone)!==JSON.stringify(start.crew[i].bone))).toBe(true);
  expect(walking.doors.some(open=>open>.5)).toBe(true);
  await page.evaluate(async()=>{for(let i=0;i<10;i++)await new Promise(requestAnimationFrame);});
  await page.screenshot({path:join(out,'station/overview.png')});
  await page.getByRole('button',{name:'Crew view'}).click();
  await page.evaluate(async()=>{for(let i=0;i<15;i++)await new Promise(requestAnimationFrame);});
  await page.screenshot({path:join(out,'station/crew-close.png')});
  await page.evaluate(()=>window.station.advance(150));
  const completed=await page.evaluate(()=>window.station.snapshot());
  expect(completed.crew.every(c=>c.completed>=2&&c.distance>10)).toBe(true);
  await page.getByRole('button',{name:'Concept',exact:false}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  expect(await page.locator('dialog img').evaluate(img=>img.complete&&img.naturalWidth>1000)).toBe(true);
  await page.getByRole('button',{name:'Close concept'}).click();
  await page.getByRole('button',{name:'Overview'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Overview'}).click();
  await page.evaluate(async()=>{for(let i=0;i<15;i++)await new Promise(requestAnimationFrame);});
  await page.screenshot({path:join(out,'station/mobile.png')});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await writeFile(join(out,'station/verification.json'),JSON.stringify({start,walking,completed,errors,desktop:[1600,1000],mobile:[390,844]},null,2));
  console.log('PASS: six departments, 36 props, three skinned characters, bone animation, navigation, task completion, concept image, desktop/mobile.');
}finally{await browser.close();}
